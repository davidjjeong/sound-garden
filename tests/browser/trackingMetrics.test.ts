import { expect, it } from 'vitest'
import { createTrackingMetrics, percentile } from '../../src/lib/trackingMetrics'
function setup() {
  let now = 0
  const metrics = createTrackingMetrics(() => now)
  return { metrics, at: (time: number) => { now = time } }
}
it('uses nearest-rank percentiles and distinguishes absent data from zero', () => {
  expect(percentile([], .95)).toBeNull()
  expect(percentile([30, 10, 20], .5)).toBe(20)
  expect(percentile([30, 10, 20], .95)).toBe(30)
  expect(percentile([0], .5)).toBe(0)
})
it('does not capture before Start or while unavailable', () => {
  const { metrics } = setup()
  metrics.setAvailable(true)
  expect(metrics.beginFrame(640, 480)).toBeNull()
  metrics.setAvailable(false)
  metrics.start()
  expect(metrics.beginFrame(640, 480)).toBeNull()
  expect(metrics.snapshot().p95Ms).toBeNull()
})
it('excludes frames begun during warm-up even if they complete afterward', () => {
  const { metrics, at } = setup()
  metrics.setAvailable(true)
  metrics.start()
  at(2990)
  const frame = metrics.beginFrame(640, 480)
  at(3020)
  metrics.finishFrame(frame, 'completed', 1)
  expect(metrics.snapshot().counts.warmupExcluded).toBe(1)
  expect(metrics.snapshot().sampleCount).toBe(0)
})
it('measures capture-to-result latency, includes no-hand results, and computes throughput', () => {
  const { metrics, at } = setup()
  metrics.setAvailable(true)
  metrics.start({ device: 'Test device' })
  at(3000)
  const first = metrics.beginFrame(640, 480)
  at(3010)
  metrics.finishFrame(first, 'completed', 0)
  at(3050)
  const second = metrics.beginFrame(640, 480)
  at(3080)
  metrics.finishFrame(second, 'completed', 1)
  at(4000)
  metrics.stop()
  const result = metrics.snapshot()
  expect(result.sampleCount).toBe(2)
  expect(result.p50Ms).toBe(10)
  expect(result.p95Ms).toBe(30)
  expect(result.resultsPerSecond).toBe(2)
  expect(result.measuredMs).toBe(1000)
  expect(result.metadata.cameraWidth).toBe(640)
  at(9000)
  expect(metrics.snapshot().measuredMs).toBe(1000)
})
it('pauses both warm-up and measurement clocks during unavailable intervals', () => {
  const { metrics, at } = setup()
  metrics.setAvailable(true)
  metrics.start()
  at(1000)
  metrics.setAvailable(false)
  at(11000)
  expect(metrics.snapshot().activeMs).toBe(1000)
  metrics.setAvailable(true)
  at(13000)
  expect(metrics.snapshot().activeMs).toBe(3000)
  expect(metrics.snapshot().measuredMs).toBe(0)
  at(14000)
  expect(metrics.snapshot().measuredMs).toBe(1000)
})
it('rejects stale visibility results and counts their exclusion exactly once', () => {
  const { metrics, at } = setup()
  metrics.setAvailable(true)
  metrics.start()
  at(3100)
  const frame = metrics.beginFrame(640, 480)
  at(3120)
  metrics.setAvailable(false, 'stale')
  metrics.setAvailable(true)
  at(3140)
  metrics.finishFrame(frame, 'completed')
  expect(metrics.snapshot().counts.stale).toBe(1)
  expect(metrics.snapshot().sampleCount).toBe(0)
})
it('Stop cancels outstanding frames, preventing late completions', () => {
  const { metrics, at } = setup()
  metrics.setAvailable(true)
  metrics.start()
  at(3100)
  const frame = metrics.beginFrame(640, 480)
  metrics.stop()
  at(3200)
  metrics.finishFrame(frame, 'completed')
  expect(metrics.snapshot().counts.canceled).toBe(1)
  expect(metrics.snapshot().sampleCount).toBe(0)
})
it('does not let an old session populate a new session even with reused frame IDs', () => {
  const { metrics, at } = setup()
  metrics.setAvailable(true)
  metrics.start()
  at(3100)
  const old = metrics.beginFrame(640, 480)
  metrics.start()
  at(6200)
  const fresh = metrics.beginFrame(640, 480)
  metrics.finishFrame(old, 'completed')
  expect(metrics.snapshot().sampleCount).toBe(0)
  metrics.finishFrame(fresh, 'completed')
  expect(metrics.snapshot().sampleCount).toBe(1)
})
it('counts failures and explicit exclusions without adding latency samples', () => {
  const { metrics, at } = setup()
  metrics.setAvailable(true)
  metrics.start()
  at(3000)
  for (const outcome of ['failed', 'canceled', 'stale'] as const) {
    const frame = metrics.beginFrame(640, 480)
    metrics.finishFrame(frame, outcome)
    metrics.finishFrame(frame, outcome)
  }
  expect(metrics.snapshot().counts).toMatchObject({ failed: 1, canceled: 1, stale: 1, attempted: 3 })
  expect(metrics.snapshot().sampleCount).toBe(0)
})
it('exports metadata, summary and raw samples and resets all session measurements', () => {
  const { metrics, at } = setup()
  metrics.setAvailable(true)
  metrics.start({ lighting: 'Daylight' })
  at(3100)
  const frame = metrics.beginFrame(640, 480)
  at(3125)
  metrics.finishFrame(frame, 'completed', 1)
  metrics.stop()
  const exported = JSON.parse(metrics.exportJson())
  expect(exported.metadata.lighting).toBe('Daylight')
  expect(exported.samples[0]).toMatchObject({ latencyMs: 25, hands: 1 })
  expect(metrics.exportCsv()).toContain('1,3100,25,1')
  metrics.reset()
  expect(metrics.snapshot()).toMatchObject({ running: false, sampleCount: 0, startedAt: null, measuredMs: 0 })
})
